"""Run the Task 2 queries on MySQL and MongoDB and save their results.

Usage (from the repository root, after both loaders have run):
    python -m scripts.run_queries

Writes, in outputs/query_results/:
    <query_id>.csv        one file per query
    QUERY_RESULTS.md      every query with its code and result table (for the report)
"""
from __future__ import annotations

import json
import re
import sys
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd
from sqlalchemy import text

from database.mongodb.queries import MONGO_QUERIES
from src import config
from src.db import mongo_collection, mysql_engine

SQL_FILE = config.ROOT_DIR / "database" / "mysql" / "queries.sql"


def parse_sql_file(path: Path) -> list[tuple[str, str, str]]:
    """Split queries.sql on '-- name: <id>' markers -> [(id, question, sql)]."""
    blocks = re.split(r"^-- name: (\S+)\s*$", path.read_text(), flags=re.M)[1:]
    queries = []
    for qid, body in zip(blocks[::2], blocks[1::2]):
        comment = [l[3:].strip() for l in body.strip().splitlines() if l.startswith("--")]
        question = re.sub(r"^Q\d\.\s*", "", " ".join(comment))
        queries.append((qid, question, body.strip()))
    return queries


def run_sql() -> list[tuple[str, str, str, pd.DataFrame]]:
    results = []
    with mysql_engine().connect() as conn:
        for qid, question, sql in parse_sql_file(SQL_FILE):
            results.append((qid, question, sql, pd.read_sql(text(sql), conn)))
    return results


def _flatten(doc: dict) -> dict:
    # weather is an array of sub-documents in Q1; show it as one readable cell
    if isinstance(doc.get("weather"), list):
        doc["weather"] = ", ".join(w.get("description", "") for w in doc["weather"])
    return doc


def run_mongo() -> list[tuple[str, str, str, pd.DataFrame]]:
    coll = mongo_collection()
    results = []
    for qid, (question, kind, spec) in MONGO_QUERIES.items():
        if kind == "find":
            cursor = coll.find(spec["filter"], spec["projection"]).sort(spec["sort"]).limit(spec["limit"])
            code = (f"db.{coll.name}.find({_js(spec['filter'])}, {_js(spec['projection'])})"
                    f".sort({_js(dict(spec['sort']))}).limit({spec['limit']})")
        else:
            cursor = coll.aggregate(spec)
            code = f"db.{coll.name}.aggregate({_js(spec)})"
        df = pd.DataFrame([_flatten(d) for d in cursor])
        # $project puts computed fields last; show columns in the order written
        projects = [s["$project"] for s in spec if "$project" in s] if kind == "aggregate" else []
        if projects:
            order = [k for k in projects[-1] if k in df.columns]
            df = df[order + [c for c in df.columns if c not in order]]
        results.append((qid, question, code, df))
    return results


def _js(obj) -> str:
    """Pretty-print a query the way it would be typed in mongosh."""
    def default(o):
        if isinstance(o, datetime):
            return f"__ISODate('{o.isoformat()}')__"
        raise TypeError(o)
    s = json.dumps(obj, indent=2, default=default)
    return re.sub(r'"__(ISODate\(.*?\))__"', r"\1", s)


def main() -> None:
    out_dir = config.QUERY_RESULTS_DIR
    out_dir.mkdir(parents=True, exist_ok=True)

    sections = {"MySQL": run_sql(), "MongoDB": run_mongo()}
    lines = ["# Task 2 - Query results", "",
             f"Generated by `python -m scripts.run_queries` on {datetime.now():%Y-%m-%d}.", ""]
    for db_name, results in sections.items():
        lang = "sql" if db_name == "MySQL" else "javascript"
        lines += [f"## {db_name}", ""]
        for i, (qid, question, code, df) in enumerate(results, 1):
            df.to_csv(out_dir / f"{qid}.csv", index=False)
            lines += [f"### Q{i}. {question}", "", f"```{lang}", code, "```", "",
                      f"Result ({len(df)} rows):", "",
                      df.to_markdown(index=False), ""]
            print(f"{qid:<32} {len(df):>3} rows")
    (out_dir / "QUERY_RESULTS.md").write_text("\n".join(lines))
    print(f"Saved results to {out_dir.relative_to(config.ROOT_DIR)}/")


if __name__ == "__main__":
    main()
